package ro.cs.tao.snap.xml;

import org.xml.sax.SAXException;
import org.xml.sax.SAXParseException;
import org.xml.sax.helpers.DefaultHandler;
import ro.cs.tao.persistence.ProcessingComponentProvider;
import ro.cs.tao.services.interfaces.WorkflowService;

import java.util.logging.Logger;

/**
 * AbstractHandler is an abstract base class that extends DefaultHandler to process SAX XML parsing events.
 * It provides common functionality for handling SAX events and stores a generic result object of type T.
 *
 * @param <T> The result type that the handler will produce after XML parsing.
 */
public abstract class AbstractHandler<T> extends DefaultHandler {
    protected final WorkflowService workflowService;
    protected final ProcessingComponentProvider processingComponentProvider;
    protected final StringBuilder buffer = new StringBuilder(512);
    protected final Logger logger = Logger.getLogger(getClass().getName());
    protected T result;

    public AbstractHandler(ProcessingComponentProvider processingComponentProvider, WorkflowService workflowService) {
        super();
        this.processingComponentProvider = processingComponentProvider;
        this.workflowService = workflowService;
    }

    /**
     * Retrieves the result of the parsing operation.
     *
     * @return the result object of type T that holds the processed data or output
     *         generated by the handler after completing its operations.
     */
    public T getResult() { return result; }

    @Override
    public void startDocument() throws SAXException {
        try {
            this.result = resultClass().newInstance();
        } catch (Exception e) {
            throw new SAXException(e);
        }
    }

    @Override
    public void endDocument() throws SAXException {
        super.endDocument();
    }

    @Override
    public void characters(char[] ch, int start, int length) throws SAXException {
        //characters() may be called several times for chunks of one element by a SAX parser
        buffer.append(ch, start, length);
    }

    @Override
    public void error(SAXParseException e) throws SAXException {
        String error = e.getMessage();
        if (!error.contains("no grammar found"))
            logger.warning(e.getMessage());
    }

    /**
     * Returns the class of the result object that this handler processes.
     *
     * @return the {@code Class} object representing the result type {@code T}
     *         that is produced by this handler.
     */
    protected abstract Class<T> resultClass();
}
